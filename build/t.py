from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b=p.chromium.launch(executable_path="/usr/bin/google-chrome")
    pg=b.new_page(viewport={"width":390,"height":844})
    errs=[]; pg.on("pageerror",lambda e:errs.append(str(e)))
    pg.goto("http://127.0.0.1:8765/#royal-tapes"); pg.wait_for_timeout(1500)
    print("login visible:", pg.is_visible("#lg"))
    pg.fill("#lgp","wrong"); pg.click("#lgb"); pg.wait_for_timeout(500); print("err:",pg.inner_text("#lge"))
    pg.fill("#lgp","test123"); pg.click("#lgb"); pg.wait_for_timeout(2500)
    print("login hidden:", not pg.is_visible("#lg"))
    pg.screenshot(path="s1.png")
    pg.click("#bottomNav [data-tab='Задачи и Codex']"); pg.wait_for_timeout(1500)
    print("tasks:", pg.inner_text("#tkDecide")[:80].replace("\n"," "))
    pg.click("#tkDecide [data-a='yes']"); pg.wait_for_timeout(1500)
    print("answered:", pg.inner_text("#tkAnswered")[:80].replace("\n"," "))
    pg.click("#bottomNav [data-tab='Счета']"); pg.wait_for_timeout(1500); pg.screenshot(path="s2.png")
    pg.reload(); pg.wait_for_timeout(2000); print("remembered:", not pg.is_visible("#lg"))
    print("errors:",errs)
    b.close()
